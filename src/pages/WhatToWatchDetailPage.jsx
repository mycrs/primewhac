
import React, { useEffect, useState } from 'react';
import { useParams, useSearchParams, useNavigate, Link } from 'react-router-dom';
import { Star, Calendar, Clock, Film, ArrowLeft, Play, Users, Loader2, AlertCircle } from 'lucide-react';
import Header from '@/components/Header';
import Footer from '@/components/Footer';
import useMovieDatabase from '@/hooks/useMovieDatabase';
import SEOHead from '@/components/SEOHead';
import SocialShareButtons from '@/components/SocialShareButtons';
import { whatToWatchDetailSchema } from '@/utils/seoSchema';
import { Button } from '@/components/ui/button';
import { Badge } from '@/components/ui/badge';
import SimilarContentSlider from '@/components/what-to-watch/SimilarContentSlider';
import { SITE_URL } from '@/constants/siteUrl';

const WhatToWatchDetailPage = ({ siteData }) => {
  const { imdbID } = useParams();
  const [searchParams] = useSearchParams();
  const type = searchParams.get('type') || 'movie';
  const navigate = useNavigate();
  const { getMovieDetails, getTVDetails, loading, error } = useMovieDatabase();
  const [content, setContent] = useState(null);

  useEffect(() => {
    const fetchData = async () => {
      if (imdbID) {
        try {
          let data;
          if (type === 'movie') {
            data = await getMovieDetails(imdbID);
          } else {
            data = await getTVDetails(imdbID);
          }
          setContent(data);
          window.scrollTo(0, 0);
        } catch (err) {
          console.error(err);
        }
      }
    };
    fetchData();
  }, [imdbID, type, getMovieDetails, getTVDetails]);

  /** Self-canonical: sorgu parametresi yok (?type=tv duplicate riski) — noindex yine pathname ile */
  const noindexCanonical =
    imdbID != null && imdbID !== ''
      ? `${SITE_URL}/ne-izlesem/${imdbID}`
      : `${SITE_URL}/ne-izlesem`;

  if (loading && !content) {
    return (
      <>
        <SEOHead title="Ne İzlesem | QruzeTV" canonicalUrl={noindexCanonical} pageData={{ isTmdb: true, isAutoGenerated: true }} />
        <div className="min-h-screen bg-[#0a0a0a] flex flex-col items-center justify-center">
          <Loader2 className="w-12 h-12 text-primary animate-spin mb-4" />
          <p className="text-slate-400">Yükleniyor...</p>
        </div>
      </>
    );
  }

  if (error || (!content && !loading)) {
    return (
      <>
        <SEOHead title="Ne İzlesem | QruzeTV" canonicalUrl={noindexCanonical} pageData={{ isTmdb: true, isAutoGenerated: true }} />
        <div className="min-h-screen bg-[#0a0a0a] flex flex-col items-center justify-center p-4">
          <AlertCircle className="w-16 h-16 text-red-500 mb-4" />
          <p className="text-red-400 mb-6 text-lg">İçerik bulunamadı veya bir hata oluştu.</p>
          <Button onClick={() => navigate('/ne-izlesem')} variant="outline" className="text-white border-slate-700">
            <ArrowLeft className="w-4 h-4 mr-2" /> Geri Dön
          </Button>
        </div>
      </>
    );
  }

  const { title, name, overview, poster_path, backdrop_path, vote_average, release_date, first_air_date, genres, runtime, episode_run_time, credits, similar } = content;
  const displayTitle = title || name;
  const year = (release_date || first_air_date)?.substring(0, 4);
  const cast = credits?.cast?.slice(0, 5) || [];
  const canonicalUrl = `${SITE_URL}/ne-izlesem/${imdbID}`;
  const hreflangOverrides = {
    tr: canonicalUrl,
    de: `${SITE_URL}/de/was-soll-ich-schauen/${imdbID}`,
  };

  const metadata = {
    title: `${displayTitle} - Ne İzlesem | QruzeTV`,
    description: (overview || `${displayTitle} hakkında detaylı bilgi. IMDb puanı, oyuncu kadrosu ve benzer içerik önerileri.`).substring(0, 160),
    keywords: [displayTitle, "film önerisi", "dizi önerisi", "ne izlesem", "IMDb", type === 'tv' ? "dizi" : "film"],
  };
  const breadcrumbSchema = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Ana Sayfa', item: `${SITE_URL}/` },
      { '@type': 'ListItem', position: 2, name: 'Ne İzlesem', item: `${SITE_URL}/ne-izlesem` },
      { '@type': 'ListItem', position: 3, name: type === 'tv' ? 'Diziler' : 'Filmler', item: `${SITE_URL}/ne-izlesem` },
      { '@type': 'ListItem', position: 4, name: displayTitle, item: canonicalUrl },
    ],
  };
  const jsonLd = [whatToWatchDetailSchema({ ...content, type }), breadcrumbSchema];

  return (
    <div className="min-h-screen bg-[#0a0a0a] text-white font-sans">
      {/* TMDB detay: noindex — hub /ne-izlesem indexlenir (WhatToWatchPage) */}
      <SEOHead
        {...metadata}
        canonicalUrl={canonicalUrl}
        hreflangOverrides={hreflangOverrides}
        jsonLd={jsonLd}
        pageData={{ isTmdb: true, isAutoGenerated: true }}
      />
      <Header contactData={siteData?.contactData} siteTexts={siteData?.siteTexts} />

      <div className="relative h-[60vh] w-full overflow-hidden">
        <div className="absolute inset-0 bg-cover bg-center opacity-30" style={{ backgroundImage: `url(https://image.tmdb.org/t/p/original${backdrop_path})` }} />
        <div className="absolute inset-0 bg-gradient-to-t from-[#0a0a0a] to-transparent" />
      </div>

      <main className="container mx-auto px-4 -mt-40 relative z-10 pb-20">
        <div className="mb-6 flex flex-wrap items-center gap-4 text-sm text-slate-400">
          <Link to="/" className="hover:text-white hover:underline">Ana sayfa</Link>
          <Link to="/ne-izlesem" className="hover:text-white hover:underline">Ne İzlesem</Link>
          <button type="button" onClick={() => navigate(`/ne-izlesem?tab=${type}`)} className="hover:text-white hover:underline">
            {type === 'tv' ? 'Diziler' : 'Filmler'}
          </button>
        </div>
        <Button onClick={() => navigate('/ne-izlesem')} variant="ghost" className="text-slate-300 hover:text-white mb-6">
          <ArrowLeft className="w-4 h-4 mr-2" /> Geri
        </Button>

        <div className="flex flex-col md:flex-row gap-8 lg:gap-12">
          <div className="w-64 md:w-80 shrink-0 mx-auto md:mx-0">
            <img src={poster_path ? `https://image.tmdb.org/t/p/w500${poster_path}` : 'https://via.placeholder.com/500x750'} alt={`${displayTitle} posteri`} className="w-full rounded-2xl shadow-2xl border border-slate-800" loading="eager" fetchPriority="high" decoding="async" />
            <Button onClick={() => navigate('/paketler')} className="w-full mt-6 bg-primary hover:bg-primary h-12 rounded-xl text-lg font-bold">
              <Play className="w-5 h-5 mr-2 fill-current" /> Hemen İzle
            </Button>
            <div className="mt-4">
              <SocialShareButtons
                url={canonicalUrl}
                title={metadata.title}
                description={metadata.description}
                image={poster_path ? `https://image.tmdb.org/t/p/w500${poster_path}` : ''}
                locale="tr"
                className="justify-center"
              />
            </div>
          </div>

          <div className="flex-1 pt-4">
            <h1 className="text-4xl md:text-5xl font-extrabold mb-4">{displayTitle}</h1>
            
            <div className="flex flex-wrap items-center gap-4 mb-6 text-slate-300">
              <div className="flex items-center gap-1 text-yellow-500 bg-yellow-500/10 px-2 py-1 rounded border border-yellow-500/20 font-bold">
                <Star className="w-4 h-4 fill-current" /> {vote_average?.toFixed(1)}
              </div>
              <span className="flex items-center gap-1"><Calendar className="w-4 h-4" /> {year}</span>
              {(runtime || episode_run_time?.[0]) && (
                <span className="flex items-center gap-1"><Clock className="w-4 h-4" /> {runtime || episode_run_time[0]} dk</span>
              )}
            </div>

            <div className="flex gap-2 mb-8 flex-wrap">
              {genres?.map(g => <Badge key={g.id} className="bg-[#0a0a0a] text-slate-300 hover:bg-[#0a0a0a]">{g.name}</Badge>)}
            </div>

            <div className="mb-10">
              <h2 className="text-xl font-bold mb-3 flex items-center gap-2"><Film className="w-5 h-5 text-primary" /> Özet</h2>
              <p className="text-slate-300 leading-relaxed text-lg">{overview || 'Bu içerik için özet bulunmuyor.'}</p>
              <div className="mt-4 flex flex-wrap gap-3 text-sm">
                <Link to="/paketler" className="text-primary hover:text-white hover:underline">IPTV paketleri</Link>
                <Link to="/ne-izlesem" className="text-primary hover:text-white hover:underline">Tüm içeriklere dön</Link>
              </div>
            </div>

            {cast.length > 0 && (
              <div className="mb-10">
                <h2 className="text-xl font-bold mb-4 flex items-center gap-2"><Users className="w-5 h-5 text-primary" /> Oyuncular</h2>
                <div className="flex gap-4 overflow-x-auto pb-4">
                  {cast.map(actor => (
                    <div key={actor.id} className="text-center w-24 shrink-0">
                      <img src={actor.profile_path ? `https://image.tmdb.org/t/p/w185${actor.profile_path}` : 'https://via.placeholder.com/150'} alt={`${actor.name} fotoğrafı`} className="w-20 h-20 rounded-full object-cover mx-auto mb-2 border-2 border-slate-800" />
                      <p className="text-sm font-bold truncate">{actor.name}</p>
                      <p className="text-xs text-slate-500 truncate">{actor.character}</p>
                    </div>
                  ))}
                </div>
              </div>
            )}
          </div>
        </div>

        {similar?.results?.length > 0 && (
          <div className="mt-20 pt-10 border-t border-slate-800">
            <h2 className="text-2xl font-bold mb-6">Benzer İçerikler</h2>
            <SimilarContentSlider items={similar.results} type={type} />
          </div>
        )}
      </main>

      <Footer contactData={siteData?.contactData} siteTexts={siteData?.siteTexts} />
    </div>
  );
};

export default WhatToWatchDetailPage;
