/**
 * TMDB poster path -> tam URL. Boşsa null döner (kart placeholder gösterir).
 */
export function buildTmdbPosterUrl(posterPath, size = 'w500') {
  if (!posterPath || typeof posterPath !== 'string') return null;
  const clean = posterPath.startsWith('/') ? posterPath : `/${posterPath}`;
  return `https://image.tmdb.org/t/p/${size}${clean}`;
}
